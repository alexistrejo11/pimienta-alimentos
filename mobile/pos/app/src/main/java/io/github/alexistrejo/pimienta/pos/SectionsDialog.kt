// Shows catalog categories in a responsive grid so all sections are visible without horizontal cutoffs.
@Composable
internal fun SectionsDialog(
    categories: List<String>,
    selected: String,
    onDismiss: () -> Unit,
    onSelect: (String) -> Unit
) {
    Dialog(
        onDismissRequest = onDismiss,
        properties = DialogProperties(usePlatformDefaultWidth = false)
    ) {
        Surface(
            shape = MaterialTheme.shapes.small,
            color = MaterialTheme.colorScheme.surface,
            modifier = Modifier
                .fillMaxWidth(0.85f)
                .widthIn(max = 760.dp)
                .heightIn(max = 520.dp)
        ) {
            Column(
                modifier = Modifier
                    .padding(20.dp)
                    .fillMaxWidth(),
                verticalArrangement = Arrangement.spacedBy(16.dp)
            ) {
                Text("Secciones del catálogo", style = MaterialTheme.typography.titleLarge)
                LazyVerticalGrid(
                    columns = GridCells.Adaptive(minSize = 135.dp),
                    horizontalArrangement = Arrangement.spacedBy(10.dp),
                    verticalArrangement = Arrangement.spacedBy(10.dp),
                    modifier = Modifier
                        .weight(1f, fill = false)
                        .fillMaxWidth()
                ) {
                    items(categories) { category ->
                        PosButton(
                            label = category,
                            click = {
                                onSelect(category)
                                onDismiss()
                            },
                            selected = selected == category,
                            modifier = Modifier.fillMaxWidth(),
                            contentPadding = PaddingValues(horizontal = 10.dp, vertical = 8.dp),
                            maxLines = 2,
                            textAlign = TextAlign.Center,
                        )
                    }
                }
                PosButton("Cerrar", onDismiss, modifier = Modifier.fillMaxWidth())
            }
        }
    }
}

